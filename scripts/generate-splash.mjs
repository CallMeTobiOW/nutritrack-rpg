// Renders iOS launch screens ("apple-touch-startup-image") so the installed app opens on a
// dark crest instead of a white flash, and writes the matching <link> tags into index.html.
// Usage: node scripts/generate-splash.mjs   (only needed if the artwork or device list changes)
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { iconSvg } from './icon.svg.mjs';

const require = createRequire(import.meta.url);
// Playwright is a dev tool, not a project dependency: resolve it from wherever it is installed.
const { chromium } = require('playwright');

// Portrait CSS size and pixel ratio of iPhones that can install home-screen web apps.
const DEVICES = [
  { w: 440, h: 956, r: 3, name: '16 Pro Max / 17 Pro Max' },
  { w: 430, h: 932, r: 3, name: '14 Pro Max / 15 Plus / 15 Pro Max / 16 Plus' },
  { w: 428, h: 926, r: 3, name: '12/13 Pro Max / 14 Plus' },
  { w: 420, h: 912, r: 3, name: 'Air' },
  { w: 414, h: 896, r: 3, name: 'XS Max / 11 Pro Max' },
  { w: 414, h: 896, r: 2, name: 'XR / 11' },
  { w: 402, h: 874, r: 3, name: '16 Pro / 17 / 17 Pro' },
  { w: 393, h: 852, r: 3, name: '14 Pro / 15 / 15 Pro / 16' },
  { w: 390, h: 844, r: 3, name: '12 / 13 / 14 / 16e' },
  { w: 375, h: 812, r: 3, name: 'X / XS / 11 Pro / 12 mini / 13 mini' },
  { w: 375, h: 667, r: 2, name: 'SE (2nd/3rd gen) / 8' },
];

const fontPath = require.resolve('@fontsource/rajdhani/files/rajdhani-latin-700-normal.woff2');
const font = readFileSync(fontPath).toString('base64');
const crest = iconSvg({ size: 132 }).replace(/<rect [^>]*\/>/, ''); // crest only, no square background

const html = `<!doctype html><html><head><style>
@font-face { font-family: Rajdhani; src: url(data:font/woff2;base64,${font}) format('woff2'); font-weight: 700; }
html, body { margin: 0; height: 100%; }
body { display: grid; place-items: center; background: #070a12; }
.c { display: flex; flex-direction: column; align-items: center; gap: 18px; transform: translateY(-4%); }
.t { font: 700 26px/1 Rajdhani, sans-serif; letter-spacing: 0.32em; padding-left: 0.32em; color: #e2e8f0; }
.s { font: 700 11px/1 Rajdhani, sans-serif; letter-spacing: 0.42em; padding-left: 0.42em; color: #f59e0b; margin-top: -8px; }
</style></head><body><div class="c">${crest}<div class="t">NUTRITRACK</div><div class="s">RPG</div></div></body></html>`;

const outDir = new URL('../public/splash/', import.meta.url);
mkdirSync(outDir, { recursive: true });
const browser = await chromium.launch();
const links = [];
for (const d of DEVICES) {
  const file = `splash-${d.w * d.r}x${d.h * d.r}.png`;
  const page = await browser.newPage({ viewport: { width: d.w, height: d.h }, deviceScaleFactor: d.r });
  await page.setContent(html);
  await page.evaluate(() => document.fonts.ready);
  writeFileSync(new URL(file, outDir), await page.screenshot());
  await page.close();
  links.push(
    `    <link rel="apple-touch-startup-image" href="splash/${file}" media="(device-width: ${d.w}px) and (device-height: ${d.h}px) and (-webkit-device-pixel-ratio: ${d.r}) and (orientation: portrait)" />`,
  );
  console.log('wrote', file, `(${d.name})`);
}
await browser.close();

const indexUrl = new URL('../index.html', import.meta.url);
const index = readFileSync(indexUrl, 'utf8');
const block = `<!-- splash:start (generated by scripts/generate-splash.mjs) -->\n${links.join('\n')}\n    <!-- splash:end -->`;
const next = /<!-- splash:start[\s\S]*?<!-- splash:end -->/.test(index)
  ? index.replace(/<!-- splash:start[\s\S]*?<!-- splash:end -->/, block)
  : index.replace('<link rel="icon"', `${block}\n    <link rel="icon"`);
writeFileSync(indexUrl, next);
console.log('updated index.html');
